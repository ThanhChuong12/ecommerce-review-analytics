"""
LazadaScraper — Network Interception by Playwright, uses pagination only.

Mechanism:
  1. Register listener page.on("response") to catch ALL review API responses
  2. Navigate + scroll -> page 1 is automatically intercepted
  3. Click "Next >" button repeatedly until out of pages or max_reviews reached

Why not replay POST manually:
  - Lazada API requires dynamic security tokens (_m_h5_tk, sign, t)
    generated by browser JS — cannot be generated externally.
  - Let browser click -> browser generates token -> we just intercept response.

URL pattern:
  https://www.lazada.vn/products/{slug}-i{itemId}-s{skuId}.html

Intercepted API endpoint:
  POST https://acs-m.lazada.vn/h5/mtop.lazada.review.item.getpcreviewlist/1.0/
"""

from __future__ import annotations

import asyncio
import hashlib
import json
import logging
import re
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlparse

from scraper.exporter import ReviewExporter
from scraper.models import Review

log = logging.getLogger("LazadaScraper")

_THIS_DIR = Path(__file__).resolve().parent.parent.parent
SESSION_DIR = _THIS_DIR / "output" / "agent_sessions"
PAGE_SIZE = 10  # fallback; actual size detected from first response

# Poll chunk wait time (seconds)
CAPTCHA_POLL_CHUNK = 10.0
# Max time to automatically wait for CAPTCHA to be solved (5 minutes)
CAPTCHA_AUTO_WAIT = 300.0

_REVIEW_PATH = "mtop.lazada.review.item.getpcreviewlist"

# Selectors for "Next page" button - Lazada uses iweb-pagination-* (not ant-)
_NEXT_PAGE_SELECTORS = [
    "li.iweb-pagination-next:not(.iweb-pagination-disabled) button",
    "li.iweb-pagination-next:not(.iweb-pagination-disabled)",
    "button.iweb-pagination-item-link[aria-label='next page']:not([disabled])",
    "button.iweb-pagination-item-link[aria-label*='next' i]:not([disabled])",
]

# Selectors to scroll to the review / pagination section
_REVIEW_SECTION_SELECTORS = [
    ".mod-reviews-pagination",
    ".iweb-pagination",
    ".pdp-mod-review-pagination-info",
    "[data-spm='pdp_reviews']",
    "#module_review",
    ".mod-reviews",
    "[class*='pdp-review']",
]


